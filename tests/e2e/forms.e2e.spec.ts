test('List View drag moves across canvases, cancels cleanly and follows selection through undo', async ({ page }) => {
  const definition = emptyDefinition()
  definition.fields = [{ id: 'a', kind: 'step', label: 'Canvas A', children: [{ id: 'question', kind: 'text', label: 'Movable question' }] }, { id: 'b', kind: 'step', label: 'Canvas B', children: [] }]
  const response = await page.request.post('/api/forms?draft=true', { data: { title: 'Drag canvases', slug: `drag-canvases-${Date.now()}`, definition } })
  const { doc } = await response.json()
  await page.goto(`/admin/collections/forms/${doc.id}`)
  const list = page.getByRole('list', { name: 'Form hierarchy' })
  const source = list.locator('[data-form-tree-row]').filter({ hasText: 'Movable question' })
  const target = list.locator('[data-form-tree-row]').filter({ hasText: 'Canvas B' })
  const drag = async (cancel: boolean) => {
    const start = (await source.boundingBox())!, end = (await target.boundingBox())!
    await page.mouse.move(start.x + start.width / 2, start.y + start.height / 2)
    await page.mouse.down()
    await page.mouse.move(start.x + start.width / 2 + 12, start.y + start.height / 2, { steps: 3 })
    await page.mouse.move(end.x + end.width / 2, end.y + end.height / 2, { steps: 10 })
    if (cancel) await page.keyboard.press('Escape')
    await page.mouse.up()
  }
  await drag(true)
  await expect(page.getByRole('button', { name: 'Undo form change' })).toBeDisabled()
  await drag(false)
  const main = page.getByRole('main', { name: 'Form canvas' })
  await expect(main.getByRole('button', { name: 'Canvas B', exact: true })).toBeVisible()
  await expect(main.getByRole('button', { name: /^Movable question/ })).toBeVisible()
  await page.getByRole('button', { name: 'Undo form change' }).click()
  await expect(main.getByRole('button', { name: 'Canvas A', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Redo form change' }).click()
  await expect(main.getByRole('button', { name: 'Canvas B', exact: true })).toBeVisible()
})
