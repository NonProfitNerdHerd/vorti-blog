import { expect, test } from '@playwright/test'

test('module sidebars route, remember close choices, and open as a mobile drawer', async ({ page }) => {
  const login = await page.request.post('/api/users/login', {
    data: { email: 'dev@payloadcms.com', password: 'test' },
  })
  expect(login.ok()).toBe(true)
  await page.goto('/admin/crm?view=overview&site=default')
  const primary = page.locator('.nav__wrap')
  for (const label of ['Tasks', 'Content', 'Intranet', 'CRM', 'Forms', 'Workflows', 'Site Design', 'Admin'])
    await expect(primary.getByRole('link', { name: label, exact: true })).toHaveCount(1)
  const crm = page.getByRole('navigation', { name: 'CRM sections' })
  await expect(crm).toBeVisible()
  await expect(page.getByRole('complementary', { name: 'CRM navigation' })).toContainText('VortiCause')
  await expect(crm.getByRole('link', { name: 'Overview' })).toHaveAttribute('aria-current', 'page')
  await page.getByRole('button', { name: 'Close CRM sidebar' }).click()
  await expect(crm).toHaveCount(0)
  await page.reload()
  await expect(crm).toHaveCount(0)
  await primary.getByRole('link', { name: 'CRM', exact: true }).hover()
  await expect(crm).toBeVisible()
  await primary.getByRole('link', { name: 'CRM', exact: true }).click()
  await expect(crm).toBeVisible()
  await primary.getByRole('link', { name: 'Content', exact: true }).click()
  await expect(page).toHaveURL(/collections\/posts.*audience=public/)
  const content = page.getByRole('navigation', { name: 'Content sections' })
  await expect(content).toBeVisible()
  await expect(content.getByRole('link', { name: 'Posts' })).toHaveAttribute('aria-current', 'page')
  await primary.getByRole('link', { name: 'Intranet', exact: true }).click()
  await expect(page).toHaveURL(/collections\/posts.*audience=intranet/)
  await expect(page.getByRole('navigation', { name: 'Intranet sections' })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByRole('navigation', { name: 'Intranet sections' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Intranet menu' }).click()
  await expect(page.getByRole('navigation', { name: 'Intranet sections' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('navigation', { name: 'Intranet sections' })).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
})
