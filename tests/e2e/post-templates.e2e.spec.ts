import { expect, test } from '@playwright/test'
test.use({ actionTimeout: 20000 })

test('template-first creation, existing creator return, independent posts and Blank', async ({ page }) => {
  await page.request.post('/api/users/login', { data: { email: 'dev@payloadcms.com', password: 'test' } })
  const count = async () => (await (await page.request.get('/api/posts/count')).json()).totalDocs as number
  const before = await count(), stamp = Date.now()
  const response = await page.request.post('/api/design-templates', { data: { name: `Article ${stamp}`, slug: `article-${stamp}`, allowedCollections: ['posts'], description: 'A reusable article introduction', status: 'published', _status: 'published', layout: [{ id: 'intro', type: 'field', fieldType: 'shortText', label: 'Introduction', content: { source: 'custom' } }] } })
  expect(response.ok(), await response.text()).toBeTruthy()
  const template = (await response.json()).doc
  await page.goto('/admin/collections/posts/create')
  let chooser = page.getByRole('dialog', { name: 'Create a Post · Choose a template', exact: true })
  await expect(chooser).toBeVisible()
  await expect(chooser.getByRole('button', { name: 'Create Post', exact: true })).toBeDisabled()
  await chooser.getByRole('button', { name: new RegExp(`Article ${stamp}`) }).click()
  await expect(chooser.getByRole('button', { name: new RegExp(`Article ${stamp}`) }).getByText('A reusable article introduction')).toBeVisible()
  await page.screenshot({ path: '.wrangler/cms-chooser-desktop.png' })
  await chooser.getByRole('button', { name: 'Create Template', exact: true }).click()
  const naming = page.getByRole('dialog', { name: 'Create a Template', exact: true })
  await expect(naming.getByRole('button', { name: 'Save name and build template' })).toBeDisabled()
  await naming.getByLabel('Template name').fill(`Article ${stamp}`)
  await naming.getByRole('button', { name: 'Save name and build template' }).click()
  await expect(naming.getByRole('alert')).toContainText('already exists')
  await naming.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(chooser.getByRole('button', { name: new RegExp(`Article ${stamp}`) })).toHaveAttribute('aria-pressed', 'true')
  expect(await count()).toBe(before)
  await chooser.getByRole('button', { name: 'Create Template', exact: true }).click()
  await naming.getByLabel('Template name').fill(`Created in chooser ${stamp}`)
  await naming.getByRole('button', { name: 'Save name and build template' }).click()
  const drawer = page.locator('.doc-drawer').last()
  await expect(drawer.getByRole('main', { name: 'Template Canvas', exact: true })).toBeVisible()
  await expect(drawer.getByRole('textbox', { name: 'Name', exact: true })).toHaveValue(`Created in chooser ${stamp}`)
  await page.keyboard.press('Escape')
  await expect(chooser).toBeVisible()
  expect(await count()).toBe(before)
  await chooser.getByRole('button', { name: 'Create Post', exact: true }).click()
  await expect(chooser).not.toBeVisible()
  await page.locator('.doc-header input[name=title]').fill(`Independent article ${stamp}`)
  await page.locator('#editor-intro').click()
  const intro = page.getByRole('region', { name: 'Introduction', exact: true }).getByRole('textbox', { name: 'Introduction', exact: true })
  await intro.fill('The Post owns this introduction')
  await page.getByRole('button', { name: 'Save Draft', exact: true }).click()
  await expect.poll(count).toBe(before + 1)
  await expect(page).toHaveURL(/\/collections\/posts\/\d+/)
  await page.reload()
  await expect(intro).toHaveValue('The Post owns this introduction')
  const previewPromise = page.waitForEvent('popup')
  await page.getByRole('link', { name: 'Preview', exact: true }).click()
  const preview = await previewPromise
  await expect(preview.getByText('The Post owns this introduction', { exact: true })).toBeVisible()
  await preview.close()
  await page.getByRole('button', { name: 'Publish changes', exact: true }).click()
  const id = page.url().match(/\/posts\/(\d+)/)![1]
  await expect.poll(async () => (await (await page.request.get(`/api/posts/${id}`)).json())._status).toBe('published')
  const published = await (await page.request.get(`/api/posts/${id}`)).json()
  expect(await (await page.request.get(`/posts/${published.slug}`)).text()).toContain('The Post owns this introduction')
  await page.goto('/admin/collections/posts/create')
  chooser = page.getByRole('dialog', { name: 'Create a Post · Choose a template', exact: true })
  await chooser.getByRole('button', { name: /Blank/ }).click()
  await chooser.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(page).toHaveURL(/\/admin\/collections\/posts(?:\?|$)/)
  expect(await count()).toBe(before + 1)
  await page.goto('/admin/collections/posts/create')
  chooser = page.getByRole('dialog', { name: 'Create a Post · Choose a template', exact: true })
  await chooser.getByRole('button', { name: /Blank/ }).click()
  await chooser.getByRole('button', { name: 'Create Post', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Add block', exact: true })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/admin/collections/posts/create')
  await expect(page.getByRole('dialog', { name: 'Create a Post · Choose a template', exact: true })).toBeVisible()
  await page.evaluate(() => document.documentElement.setAttribute('data-theme', 'dark'))
  await page.screenshot({ path: '.wrangler/cms-chooser-mobile-dark.png' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})
