import { SiteAccessError } from '../organizations/repository'
import { OrganizationRepository } from '../organizations/repository'
import { scopeImportExport } from './import-exports'
import { importExportMismatch } from './import-export-job'
import { importReferenceRules } from './import-context'
import { importedRecordExistsV1 } from './import-records-v1'

/** Revalidate the retained, previously authenticated review snapshots in one
 * current SQL snapshot. No per-source-row application round trips are needed.
 * Normal review writers atomically change revision/hash with their JSON; the
 * immutable chunk manifest binds those exact revisions/hashes to generated bytes.
 */
export async function assertImportExportReadable(
  db: D1Database,
  actor: number,
  siteID: string,
  id: string,
) {
  const scoped = await scopeImportExport(db, actor, siteID, id),
    { file, run, site } = scoped,
    grants = await new OrganizationRepository(db, actor).authoritySet(siteID)
  if (grants.authorityRevision !== site.authorityRevision) throw new SiteAccessError()
  const allowed = Object.entries(importReferenceRules)
    .filter(([, rule]) => grants.allowed[rule.category]?.includes('read'))
    .map(([kind]) => kind)
  const references = Object.entries(importReferenceRules)
    .map(([kind, rule]) => {
      let parameter = 0
      const sql = rule.sql.replace(/\?/g, () =>
        ++parameter === 1 ? 'r.site_id' : "json_extract(ref.value,'$.id')",
      )
      return `(json_extract(ref.value,'$.kind')='${kind}' AND EXISTS(${sql}))`
    })
    .join(' OR ')
  const target =
      "coalesce(r.applied_id,CASE WHEN json_type(r.review_json,'$.before')<>'null' THEN json_extract(r.review_json,'$.targetID') END)",
    targetVisible = importedRecordExistsV1('r.domain', 'r.site_id', target)
  const result = await db
    .prepare(
      `WITH selected AS(SELECT r.*,u.domain,u.site_id,u.actor_id,u.source_system FROM vc_crm_import_export_chunks chunk JOIN json_each(chunk.snapshots) snapshot
      JOIN vc_crm_import_rows r ON r.run_id=? AND r.number=json_extract(snapshot.value,'$.number') JOIN vc_crm_import_runs u ON u.id=r.run_id WHERE chunk.export_id=?),
    manifest AS(SELECT count(*) AS chunks,coalesce(sum(rows),0) AS rows,min(ordinal) AS first,max(ordinal) AS last FROM vc_crm_import_export_chunks WHERE export_id=?)
    SELECT CASE WHEN (SELECT chunks>0 AND rows=? AND first=0 AND last=chunks-1 FROM manifest)
      AND NOT EXISTS(SELECT 1 FROM vc_crm_import_export_chunks WHERE export_id=? AND deleted_at IS NOT NULL)
      AND ${importExportMismatch}
      AND NOT EXISTS(SELECT 1 FROM selected r WHERE r.review_hash IS NOT NULL AND(
        json_extract(r.review_json,'$.version') IS NOT 1 OR json_extract(r.review_json,'$.actor') IS NOT r.actor_id
        OR json_extract(r.review_json,'$.site') IS NOT r.site_id OR json_extract(r.review_json,'$.domain') IS NOT r.domain
        OR json_extract(r.review_json,'$.sourceSystem') IS NOT r.source_system
        OR json_type(r.review_json,'$.visibility.references') IS NOT 'array' OR json_type(r.review_json,'$.visibility.contacts') IS NOT 'array'
        OR EXISTS(SELECT 1 FROM json_each(r.review_json,'$.visibility.references') ref WHERE coalesce((json_type(ref.value,'$.id')='text'
          AND json_extract(ref.value,'$.kind') IN(SELECT value FROM json_each(?)) AND(${references})),0)=0)
        OR EXISTS(SELECT 1 FROM json_each(r.review_json,'$.visibility.contacts') contact WHERE contact.type<>'text' OR NOT EXISTS(
          SELECT 1 FROM vc_crm_constituents c JOIN vc_crm_affiliations a ON a.constituent_id=c.id AND a.organization_id=c.organization_id WHERE a.site_id=r.site_id AND a.archived=0 AND c.archived=0 AND c.id=contact.value))
        OR(${target} IS NOT NULL AND NOT(${targetVisible}))
      )) THEN 1 ELSE 0 END AS visible`,
    )
    .bind(
      run.id,
      file.id,
      file.id,
      file.expected_rows,
      file.id,
      run.id,
      file.id,
      JSON.stringify(allowed),
    )
    .first<{ visible: number }>()
  if (result?.visible !== 1) throw new SiteAccessError()
  const current = await scopeImportExport(db, actor, siteID, id)
  if (current.site.authorityRevision !== site.authorityRevision) throw new SiteAccessError()
  return scoped
}
